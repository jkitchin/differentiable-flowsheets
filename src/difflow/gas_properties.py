"""Gas viscosity, thermal conductivity, heat capacity and Prandtl number.

Low-pressure (1 atm) transport properties of common gases, differentiable in
temperature, for convection correlations (``difflow.heat_transfer``) and gas
pipe flow. Each property is a fit

    ln y = sum_i c_i x^i,    x = ln(T / 300 K)

(cubic for viscosity and conductivity, quintic for heat capacity) to
tabulated data, generated by ``scripts/fit_gas_transport.py`` from the
committed tables:

- nitrogen, oxygen, argon, carbon_dioxide, carbon_monoxide, methane,
  hydrogen, helium and water (vapour): the NIST Chemistry WebBook (SRD 69)
  1 atm isobars (``tests/reference/nist_gases_1atm/``). Max deviations:
  viscosity 0.16 %, conductivity 0.5 % (methane), heat capacity 0.06 %
  (0.14 % for steam).
- air: Engineering ToolBox tables for dry air at 1 atm (viscosity and
  conductivity, 223-1273 K, ``tests/reference/air_engineering_toolbox.csv``)
  and the mass-weighted NIST heat capacity of N2/O2/Ar (78.12/20.96/0.92
  mol %). At 300 K this gives mu = 18.46 uPa s, k = 26.4 mW/m/K, cp = 1007 J/kg/K and Pr = 0.704,
  against Incropera Table A.4: 18.46 uPa s, 26.3 mW/m/K, 1007 J/kg/K and
  0.707. Table A.4's densities (hence nu and alpha) are at 1 bar, not
  1 atm; pass ``P=1e5`` to compare them (the 1 atm default is 1.3 % denser).

The fits are for the dilute gas, with no dense-gas correction and no mixture
rule. Viscosity and conductivity hardly change with pressure up to about
10 bar, except near saturation or the critical point; above that they rise
(methane at 15 C: 10.75 uPa s dilute, about 12.0 at 50 bar). Heat capacity is
the 1 atm value. Each fit is valid over the data range
(``gas_property_range``); a concrete temperature outside it raises
:class:`GasRangeWarning`, and the value is extrapolated, never clipped.

For a gas without data, :func:`sutherland_viscosity` and
:func:`sutherland_conductivity` take the Sutherland-law constants of White,
*Viscous Fluid Flow* (3e, Tables 1-2 and 1-3), in :data:`SUTHERLAND`. These
are good to about 2 % over moderate ranges.

Example:
    >>> from difflow.gas_properties import gas_viscosity, gas_prandtl
    >>> round(float(gas_viscosity("nitrogen", 300.0)) * 1e6, 2)
    17.89
    >>> round(float(gas_prandtl("air", 300.0)), 3)
    0.704
"""

