# White, Viscous Fluid Flow, 3e (McGraw-Hill 2006), Tables 1-2 (viscosity)
# and 1-3 (conductivity): mu = mu0 (T/T0)^1.5 (T0 + S)/(T + S), T0 = 273 K.
