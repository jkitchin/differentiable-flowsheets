def list_gas_species() -> list[str]:
    """Names with fitted gas properties."""
    return sorted(_GAS_FITS)


def _name(name: str) -> str:
    key = name.strip().lower()
    key = _ALIASES.get(key, key)
    if key not in _GAS_FITS:
        raise KeyError(
            f"No gas transport data for {name!r}; have {list_gas_species()}. "
            "For another gas use sutherland_viscosity / sutherland_conductivity.")
    return key


def gas_property_range(name: str, prop: str = "mu") -> tuple[float, float]:
    """``(Tmin, Tmax)`` in K of the data behind a fit (prop ``mu``, ``k`` or ``cp``)."""
    _, lo, hi = _GAS_FITS[_name(name)][prop]
    return lo, hi


def _warn_range(name, prop, T, lo, hi):
    if isinstance(T, jax.core.Tracer):
        return
    try:
        Tmin, Tmax = float(jnp.min(T)), float(jnp.max(T))
    except Exception:  # noqa: BLE001 -- abstract values under transforms
        return
    if Tmin < lo or Tmax > hi:
        warnings.warn(
            f"{name} gas {prop} at T outside [{lo:g}, {hi:g}] K (data range); extrapolating",
            GasRangeWarning, stacklevel=3)


def _eval(name: str, prop: str, T) -> Array:
    key = _name(name)
    coeffs, lo, hi = _GAS_FITS[key][prop]
    _warn_range(key, prop, T, lo, hi)
    T = jnp.asarray(T, dtype=jnp.float64)
    x = jnp.log(T / 300.0)
    acc = jnp.zeros_like(x)
    for c in reversed(coeffs):
        acc = acc * x + c
    return jnp.exp(acc)


def gas_viscosity(name: str, T: Array | float) -> Array:
    """Dynamic viscosity of a gas at low pressure (Pa s).

    Args:
        name: Gas name (``list_gas_species()``) or formula alias (``"N2"``,
            ``"CO2"``, ``"CH4"``, ``"H2O"``/``"steam"``, ...).
        T: Temperature (K), scalar or array.

    Returns:
        Viscosity (Pa s).

    Example:
        >>> round(float(gas_viscosity("CH4", 300.0)) * 1e6, 1)   # NIST: 11.1
        11.1
    """
    return _eval(name, "mu", T)


def gas_thermal_conductivity(name: str, T: Array | float) -> Array:
    """Thermal conductivity of a gas at low pressure (W/m/K).

    Args:
        name: Gas name or alias, as for :func:`gas_viscosity`.
        T: Temperature (K).

    Returns:
        Thermal conductivity (W/m/K).

    Example:
        >>> round(float(gas_thermal_conductivity("air", 300.0)) * 1e3, 1)
        26.4
    """
    return _eval(name, "k", T)


def gas_heat_capacity(name: str, T: Array | float) -> Array:
    """Isobaric heat capacity of a gas at 1 atm (J/kg/K).

    Args:
        name: Gas name or alias.
        T: Temperature (K).

    Returns:
        cp (J/kg/K).

    Example:
        >>> round(float(gas_heat_capacity("air", 300.0)))
        1007
    """
    return _eval(name, "cp", T)


def gas_prandtl(name: str, T: Array | float) -> Array:
    """Prandtl number ``cp mu / k`` of a gas at 1 atm.

    Args:
        name: Gas name or alias.
        T: Temperature (K).

    Returns:
        Pr (-).

    Example:
        >>> round(float(gas_prandtl("air", 300.0)), 3)   # Incropera A.4: 0.707
        0.704
    """
    return gas_heat_capacity(name, T) * gas_viscosity(name, T) / gas_thermal_conductivity(name, T)


def gas_density(name: str, T: Array | float, P: Array | float = 101325.0) -> Array:
    """Ideal-gas density ``P MW / (R T)`` (kg/m^3).

    Args:
        name: Gas name or alias.
        T: Temperature (K).
        P: Pressure (Pa), default 1 atm.

    Returns:
        Density (kg/m^3).
    """
    MW = _GAS_FITS[_name(name)]["MW"]
    return jnp.asarray(P, dtype=jnp.float64) * MW * 1e-3 / (R_GAS * jnp.asarray(T, dtype=jnp.float64))


def gas_kinematic_viscosity(name: str, T: Array | float, P: Array | float = 101325.0) -> Array:
    """Kinematic viscosity ``mu / rho`` (m^2/s), ideal-gas density.

    Args:
        name: Gas name or alias.
        T: Temperature (K).
        P: Pressure (Pa), default 1 atm.

    Returns:
        nu (m^2/s).
    """
    return gas_viscosity(name, T) / gas_density(name, T, P)


def gas_transport_properties(name: str, T: Array | float, P: Array | float = 101325.0) -> dict:
    """All gas properties at once.

    Args:
        name: Gas name or alias.
        T: Temperature (K).
        P: Pressure (Pa) for the density, default 1 atm.

    Returns:
        ``{'mu', 'k', 'cp', 'Pr', 'rho', 'nu', 'alpha'}`` (SI; ``alpha`` the
        thermal diffusivity ``k/(rho cp)``).
    """
    mu = gas_viscosity(name, T)
    k = gas_thermal_conductivity(name, T)
    cp = gas_heat_capacity(name, T)
    rho = gas_density(name, T, P)
    return {"mu": mu, "k": k, "cp": cp, "Pr": cp * mu / k, "rho": rho,
            "nu": mu / rho, "alpha": k / (rho * cp)}


def _sutherland(T, y0, T0, S):
    T = jnp.asarray(T, dtype=jnp.float64)
    return y0 * (T / T0) ** 1.5 * (T0 + S) / (T + S)


def sutherland_viscosity(T: Array | float, gas: str | None = None, *, mu0: float | None = None,
                         T0: float = 273.0, S: float | None = None) -> Array:
    """Sutherland's law ``mu = mu0 (T/T0)^1.5 (T0 + S)/(T + S)`` (Pa s).

    Args:
        T: Temperature (K).
        gas: A key of :data:`SUTHERLAND` (White's constants), or None to give
            ``mu0``, ``T0`` and ``S`` directly.
        mu0: Reference viscosity (Pa s) at ``T0``.
        T0: Reference temperature (K).
        S: Sutherland constant (K).

    Returns:
        Viscosity (Pa s).

    Example:
        >>> round(float(sutherland_viscosity(300.0, "air")) * 1e6, 2)
        18.47
    """
    if gas is not None:
        c = SUTHERLAND[_ALIASES.get(gas.lower(), gas.lower())]
        mu0, T0, S = c["mu0"], c["T0"], c["S_mu"]
    if mu0 is None or S is None:
        raise ValueError("give gas= or both mu0= and S=")
    return _sutherland(T, mu0, T0, S)


def sutherland_conductivity(T: Array | float, gas: str | None = None, *, k0: float | None = None,
                            T0: float = 273.0, S: float | None = None) -> Array:
    """Sutherland's law for thermal conductivity (W/m/K); see :func:`sutherland_viscosity`.

    Args:
        T: Temperature (K).
        gas: A key of :data:`SUTHERLAND`, or None to give ``k0``, ``T0``, ``S``.
        k0: Reference conductivity (W/m/K) at ``T0``.
        T0: Reference temperature (K).
        S: Sutherland constant for conductivity (K).

    Returns:
        Thermal conductivity (W/m/K).
    """
    if gas is not None:
        c = SUTHERLAND[_ALIASES.get(gas.lower(), gas.lower())]
        k0, T0, S = c["k0"], c["T0"], c["S_k"]
    if k0 is None or S is None:
        raise ValueError("give gas= or both k0= and S=")
    return _sutherland(T, k0, T0, S)
