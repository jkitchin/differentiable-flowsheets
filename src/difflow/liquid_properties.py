#: Property keys and their names in messages.
PROPERTIES = {"rho": "density", "mu": "viscosity", "k": "thermal conductivity"}

# Smallest (1 - T/Tc) used in the critical-point guard.
_TAU_MIN = 1e-10


class LiquidRangeWarning(UserWarning):
    """A liquid property was evaluated outside its correlation's range."""


class LiquidCorrelation(NamedTuple):
    """One temperature correlation for a liquid property.

    Attributes:
        form: Equation form, one of the forms in the module docstring.
        coeffs: Coefficients, in the order the form lists them.
        Tmin: Lower end of the valid range (K).
        Tmax: Upper end of the valid range (K).
        range_stated: True if the source states this range; False if it was
            assumed (melting point to Tc for VDI-PPDS density and thermal
            conductivity; derived from the equation for PPDS9 viscosity; the
            method's usual range for an estimate).
        source: Key into the source citations; see
            :func:`liquid_property_source`.
    """

    form: str
    coeffs: tuple
    Tmin: float
    Tmax: float
    range_stated: bool
    source: str


class LiquidPropertyData(NamedTuple):
    """Liquid-property correlations for a pure species.

    Attributes:
        name: Species identifier (difflow database key).
        CAS: CAS registry number.
        MW: Molecular weight (g/mol), the database value.
        Tm: Melting point (K).
        rho: Density correlation.
        mu: Viscosity correlation.
        k: Thermal-conductivity correlation.
    """

    name: str
    CAS: str
    MW: float
    Tm: float
    rho: LiquidCorrelation
    mu: LiquidCorrelation
    k: LiquidCorrelation


def _correlation(d: dict) -> LiquidCorrelation:
    return LiquidCorrelation(d["form"], tuple(d["coeffs"]), d["Tmin"],
                             d["Tmax"], d["range_stated"], d["source"])


def list_liquid_species() -> list[str]:
    """Species with liquid-property data, sorted."""
    return sorted(LIQUID_DATA)


def get_liquid_properties(name: str) -> LiquidPropertyData:
    """Liquid-property correlations for a species (aliases accepted).

    Args:
        name: Species name or alias, as for ``get_species_data``.

    Returns:
        LiquidPropertyData.

    Raises:
        KeyError: If the species has no liquid-property data.

    Example:
        >>> get_liquid_properties("water").rho.source
        'vdi_ppds'
    """
    from difflow.database import _record_access, resolve_alias

    _record_access(name, "liquid")
    key = resolve_alias(name)
    if key not in LIQUID_DATA:
        raise KeyError(
            f"No liquid-property data for '{name}'. Available: "
            + ", ".join(list_liquid_species()))
    d = LIQUID_DATA[key]
    return LiquidPropertyData(
        name=key, CAS=d["CAS"], MW=d["MW"], Tm=d["Tm"],
        rho=_correlation(d["rho"]), mu=_correlation(d["mu"]),
        k=_correlation(d["k"]))


def _data(species: str | LiquidPropertyData) -> LiquidPropertyData:
    if isinstance(species, LiquidPropertyData):
        return species
    return get_liquid_properties(species)


def _tau(T: Array, Tc: float) -> Array:
    return jnp.maximum(1.0 - T / Tc, _TAU_MIN)


def evaluate_correlation(corr: LiquidCorrelation, T: Array | float) -> Array:
    """Evaluate a correlation in its native units, without range checks.

    Args:
        corr: The correlation.
        T: Temperature (K), scalar or array.

    Returns:
        mol/m^3 for density forms, Pa s for viscosity, W/m/K for thermal
        conductivity.
    """
    T = jnp.asarray(T, dtype=jnp.float64)
    p = corr.coeffs
    form = corr.form
    if form == "DIPPR105":
        A, B, C, D = p
        return A / B ** (1.0 + _tau(T, C) ** D)
    if form == "PPDS10":
        Tc, rhoc, a, b, c, d, MW = p
        tau = _tau(T, Tc)
        rho = (rhoc + a * tau**0.35 + b * tau ** (2.0 / 3.0) + c * tau
               + d * tau ** (4.0 / 3.0))
        return rho / MW * 1e3
    if form == "DIPPR101":
        A, B, C, D, E = p
        return jnp.exp(A + B / T + C * jnp.log(T) + D * T**E)
    if form == "PPDS9":
        A, B, C, D, E = p
        X = (C - T) / (T - D)
        X13 = jnp.cbrt(X)
        return E * jnp.exp(A * X13 + B * X * X13)
    if form == "DIPPR100":
        A, B, C, D, E = p
        return A + T * (B + T * (C + T * (D + T * E)))
    if form == "SATO_RIEDEL":
        MW, Tc, Tb = p
        num = 3.0 + 20.0 * _tau(T, Tc) ** (2.0 / 3.0)
        den = 3.0 + 20.0 * (1.0 - Tb / Tc) ** (2.0 / 3.0)
        return 1.1053 * num / (den * jnp.sqrt(MW))
    raise ValueError(f"unknown liquid correlation form {form!r}")


def check_liquid_range(species: str | LiquidPropertyData,
                       T: float) -> dict[str, dict]:
    """Report whether a temperature is inside each correlation's range.

    Args:
        species: Species name or LiquidPropertyData.
        T: Temperature (K), concrete.

    Returns:
        ``{prop: {'in_range', 'T_min', 'T_max', 'range_stated'}}`` for
        prop in ``'rho'``, ``'mu'``, ``'k'``.
    """
    data = _data(species)
    T = float(T)
    return {
        prop: {"in_range": c.Tmin <= T <= c.Tmax, "T_min": c.Tmin,
               "T_max": c.Tmax, "range_stated": c.range_stated}
        for prop, c in (("rho", data.rho), ("mu", data.mu), ("k", data.k))
    }


def _warn_out_of_range(data: LiquidPropertyData, prop: str, T) -> None:
    """Warn when a concrete T leaves the correlation's range (not under jit)."""
    if isinstance(T, jax.core.Tracer):
        return
    try:
        values = np.asarray(T, dtype=float)
    except Exception:
        return
    corr = getattr(data, prop)
    lo, hi = float(values.min()), float(values.max())
    if lo < corr.Tmin or hi > corr.Tmax:
        stated = "" if corr.range_stated else " (assumed range)"
        warnings.warn(
            f"{data.name} liquid {PROPERTIES[prop]} evaluated at "
            f"T = {lo:g}-{hi:g} K, outside {corr.Tmin:g}-{corr.Tmax:g} K"
            f"{stated} of its {corr.form} correlation; the value is an "
            "extrapolation.",
            LiquidRangeWarning, stacklevel=3)


def liquid_molar_density(species: str | LiquidPropertyData,
                         T: Array | float) -> Array:
    """Saturated-liquid molar density (mol/m^3).

    Args:
        species: Species name or LiquidPropertyData.
        T: Temperature (K).

    Returns:
        Molar density, mol/m^3.

    Example:
        >>> round(float(liquid_molar_density("water", 298.15)))
        55342
    """
    data = _data(species)
    _warn_out_of_range(data, "rho", T)
    return evaluate_correlation(data.rho, T)


def liquid_density(species: str | LiquidPropertyData,
                   T: Array | float) -> Array:
    """Saturated-liquid mass density (kg/m^3).

    Args:
        species: Species name or LiquidPropertyData.
        T: Temperature (K).

    Returns:
        Density, kg/m^3.

    Example:
        >>> round(float(liquid_density("ethanol", 298.15)), 1)  # measured 785.1
        786.0
    """
    data = _data(species)
    return liquid_molar_density(data, T) * data.MW * 1e-3


def liquid_viscosity(species: str | LiquidPropertyData,
                     T: Array | float) -> Array:
    """Liquid dynamic viscosity (Pa s).

    Args:
        species: Species name or LiquidPropertyData.
        T: Temperature (K).

    Returns:
        Viscosity, Pa s.

    Example:
        >>> 8.0e-4 < float(liquid_viscosity("water", 298.15)) < 9.5e-4
        True
    """
    data = _data(species)
    _warn_out_of_range(data, "mu", T)
    return evaluate_correlation(data.mu, T)


def liquid_thermal_conductivity(species: str | LiquidPropertyData,
                                T: Array | float) -> Array:
    """Liquid thermal conductivity (W/m/K).

    Args:
        species: Species name or LiquidPropertyData.
        T: Temperature (K).

    Returns:
        Thermal conductivity, W/m/K.

    Example:
        >>> 0.59 < float(liquid_thermal_conductivity("water", 298.15)) < 0.62
        True
    """
    data = _data(species)
    _warn_out_of_range(data, "k", T)
    return evaluate_correlation(data.k, T)


def liquid_property_source(species: str | LiquidPropertyData,
                           prop: str) -> str:
    """Citation for one of a species' liquid-property correlations.

    Args:
        species: Species name or LiquidPropertyData.
        prop: ``'rho'``, ``'mu'`` or ``'k'``.

    Returns:
        The citation string.
    """
    if prop not in PROPERTIES:
        raise ValueError(f"prop must be one of {list(PROPERTIES)}, got {prop!r}")
    return SOURCES[getattr(_data(species), prop).source]


