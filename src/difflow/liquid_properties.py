"""Liquid density, viscosity and thermal conductivity, differentiable in JAX.

Every built-in species (``difflow.database.list_species()``) has one
correlation for each property. The coefficients come from published tables
(VDI Heat Atlas PPDS sets and Perry's 8th edition, as tabulated by the
`chemicals` package), from estimates built on data difflow already stores, or
for heavy water from a fit to CoolProp. They are generated by
``scripts/generate_liquid_properties.py`` into ``_liquid_property_data.py``;
neither `chemicals` nor CoolProp is needed at runtime. See issue #406 for how
the sources were chosen and how well each agrees with CoolProp.

Units: temperature K; density kg/m^3 (``liquid_density``) or mol/m^3
(``liquid_molar_density``); viscosity Pa s; thermal conductivity W/m/K.

Correlation forms (``LiquidCorrelation.form``):

- ``DIPPR105``: rho_molar = A / B^(1 + (1 - T/C)^D), mol/m^3.
- ``PPDS10``: rho_mass = rho_c + a tau^0.35 + b tau^(2/3) + c tau + d tau^(4/3),
  tau = 1 - T/Tc, kg/m^3; coefficients (Tc, rho_c, a, b, c, d, MW).
- ``DIPPR101``: mu = exp(A + B/T + C ln T + D T^E), Pa s.
- ``PPDS9``: mu = E exp(A X^(1/3) + B X^(4/3)), X = (C - T)/(T - D), Pa s.
- ``DIPPR100``: k = A + B T + C T^2 + D T^3 + E T^4, W/m/K.
- ``SATO_RIEDEL``: k = 1.1053 (3 + 20 (1 - Tr)^(2/3)) / (sqrt(MW)
  (3 + 20 (1 - Tbr)^(2/3))), coefficients (MW, Tc, Tb), W/m/K.

Each correlation carries the temperature range it is valid over. A concrete
temperature outside it raises :class:`LiquidRangeWarning`; the value is still
the correlation's, never clipped, so gradients stay smooth. (The one guard is
at the critical temperature in the forms that contain (1 - T/Tc)^n, where a
liquid no longer exists and the power would be NaN.)

Example:
    >>> from difflow.liquid_properties import liquid_density, liquid_viscosity
    >>> round(float(liquid_density("water", 298.15)), 1)
    997.0
    >>> mu = liquid_viscosity("water", 298.15)   # ~8.9e-4 Pa s
"""

from __future__ import annotations

import warnings
from collections.abc import Mapping
from typing import NamedTuple

import jax
import jax.numpy as jnp
import numpy as np
from jax import Array

from difflow._liquid_property_data import LIQUID_DATA, SOURCES

