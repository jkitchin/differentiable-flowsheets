def _composition(mole_fractions: Mapping[str, Array | float]):
    names = list(mole_fractions)
    x = jnp.stack([jnp.asarray(mole_fractions[n], dtype=jnp.float64)
                   for n in names])
    x = x / jnp.sum(x, axis=0)
    data = [get_liquid_properties(n) for n in names]
    return data, x


def mixture_liquid_molar_density(mole_fractions: Mapping[str, Array | float],
                                 T: Array | float) -> Array:
    """Liquid-mixture molar density by ideal mixing of molar volumes (mol/m^3).

    1/rho_mix = sum_i x_i / rho_i. Excess volume is neglected; for
    water-alcohol mixtures that underestimates density by up to ~3%.

    Args:
        mole_fractions: ``{species: x_i}``; normalized here.
        T: Temperature (K).

    Returns:
        Molar density, mol/m^3.
    """
    data, x = _composition(mole_fractions)
    v = jnp.stack([1.0 / liquid_molar_density(d, T) for d in data])
    return 1.0 / jnp.sum(x * v, axis=0)


def mixture_liquid_density(mole_fractions: Mapping[str, Array | float],
                           T: Array | float) -> Array:
    """Liquid-mixture mass density (kg/m^3), ideal mixing of molar volumes.

    Args:
        mole_fractions: ``{species: x_i}``; normalized here.
        T: Temperature (K).

    Returns:
        Density, kg/m^3.
    """
    data, x = _composition(mole_fractions)
    MW = jnp.array([d.MW for d in data]).reshape((-1,) + (1,) * (x.ndim - 1))
    return (mixture_liquid_molar_density(mole_fractions, T)
            * jnp.sum(x * MW, axis=0) * 1e-3)


def mixture_liquid_viscosity(mole_fractions: Mapping[str, Array | float],
                             T: Array | float) -> Array:
    """Liquid-mixture viscosity by the log-linear rule (Pa s).

    ln mu_mix = sum_i x_i ln mu_i (Grunberg-Nissan with no interaction
    term). Good for similar nonpolar liquids; for aqueous or hydrogen-bonding
    mixtures the true viscosity can be well above this.

    Args:
        mole_fractions: ``{species: x_i}``; normalized here.
        T: Temperature (K).

    Returns:
        Viscosity, Pa s.
    """
    data, x = _composition(mole_fractions)
    ln_mu = jnp.stack([jnp.log(liquid_viscosity(d, T)) for d in data])
    return jnp.exp(jnp.sum(x * ln_mu, axis=0))


def mixture_liquid_thermal_conductivity(
        mole_fractions: Mapping[str, Array | float],
        T: Array | float) -> Array:
    """Liquid-mixture thermal conductivity by DIPPR procedure 9H (W/m/K).

    k_mix = (sum_i w_i / k_i^2)^(-1/2), with mass fractions w_i. DIPPR
    advises against it when the pure-component k differ by more than a
    factor of two, as in most aqueous mixtures.

    Args:
        mole_fractions: ``{species: x_i}``; normalized here.
        T: Temperature (K).

    Returns:
        Thermal conductivity, W/m/K.
    """
    data, x = _composition(mole_fractions)
    MW = jnp.array([d.MW for d in data]).reshape((-1,) + (1,) * (x.ndim - 1))
    w = x * MW / jnp.sum(x * MW, axis=0)
    k = jnp.stack([liquid_thermal_conductivity(d, T) for d in data])
    return jnp.sum(w / k**2, axis=0) ** -0.5


def stream_liquid_properties(stream: Mapping[str, Array]) -> dict[str, Array]:
    """Liquid properties of a stream at its temperature.

    Treats the whole stream as liquid; species with zero flow drop out of
    the mixing rules.

    Args:
        stream: A difflow stream (``F_<species>`` flows in mol/s and ``T``).

    Returns:
        ``{'rho', 'rho_molar', 'mu', 'k'}`` in kg/m^3, mol/m^3, Pa s and
        W/m/K, plus ``'Q'``, the volumetric flow (m^3/s).

    Example:
        >>> from difflow import make_stream
        >>> s = make_stream({"water": 10.0}, T=298.15, P=101325.0)
        >>> round(float(stream_liquid_properties(s)["Q"] * 1e6), 1)  # cm^3/s
        180.7
    """
    flows = {k[2:]: v for k, v in stream.items() if k.startswith("F_")}
    T = stream["T"]
    F = sum(flows.values())
    rho_molar = mixture_liquid_molar_density(flows, T)
    return {
        "rho": mixture_liquid_density(flows, T),
        "rho_molar": rho_molar,
        "mu": mixture_liquid_viscosity(flows, T),
        "k": mixture_liquid_thermal_conductivity(flows, T),
        "Q": F / rho_molar,
    }
